def _best(with_rental: bool):
    best = (Fraction(-1), None)
    for a in range(0, _land['A']['area'] + 1):
        for d in range(0, _land['D']['area'] + 1):
            if with_rental:
                bmax = min(_land['B']['area'], floor(200 - Fraction(a * 200, 330) - Fraction(d * 200, 400)))
                bs = [bmax] if bmax >= 1 else []
